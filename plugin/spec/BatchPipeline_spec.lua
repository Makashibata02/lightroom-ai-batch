require 'spec_helper'
local helper = require 'batch_test_helper'

describe("BatchPipeline fault isolation", function()
    local sdk, pipeline
    before_each(function() sdk = helper.new(); pipeline = require 'BatchPipeline' end)
    after_each(function() sdk.restore() end)

    it("fails an unavailable photo and completes the following RAW", function()
        sdk.select({ sdk.photo(1, { available = false }), sdk.photo(2) })
        local submitted = pipeline.start({ profile = "full" })
        assert.are.equal("QUEUED", submitted.status)
        sdk.advance(30)
        local result = pipeline.status({ jobId = submitted.jobId })
        assert.are.equal("COMPLETE", result.status)
        assert.are.equal(1, result.failed)
        assert.are.equal(1, result.completed)
        assert.are.same({ 2 }, sdk.enhanceCalls)
        assert.is_false(result.workerRunning)
        assert.are.same({ sdk.photos[1], sdk.photos[2] }, sdk.selection)
    end)

    it("isolates an AI mask error and allows a new batch without restart", function()
        sdk.select({ sdk.photo(1), sdk.photo(2) })
        sdk.maskHook = function(photo) if photo.localIdentifier == 1 then error("cannot display photo") end end
        local submitted = pipeline.start({ profile = "full" })
        sdk.advance(30)
        local result = pipeline.status({ jobId = submitted.jobId })
        assert.are.equal(1, result.failed)
        assert.are.equal(1, result.completed)
        assert.is_false(result.workerRunning)
        assert.is_false(result.restartRequired)
        sdk.select({ sdk.photo(3) })
        local nextJob = pipeline.start({ profile = "full" })
        sdk.advance(20)
        assert.are.equal(1, pipeline.status({ jobId = nextJob.jobId }).completed)
        assert.are.same({ 1, 2, 3 }, sdk.enhanceCalls)
    end)

    it("does not recover Denoise after a failed AI mask call", function()
        sdk.select({ sdk.photo(1) })
        sdk.maskHook = function(photo) photo.available = false; error("mask renderer error") end
        local submitted = pipeline.start({ profile = "full" })
        sdk.advance(20)
        local result = pipeline.status({ jobId = submitted.jobId })
        assert.are.equal(1, result.failed)
        assert.are.same({ 1 }, sdk.enhanceCalls)
        assert.is_false(result.photos[1].denoiseValidation.recoveryAttempted)
    end)

    it("quarantines hung native work, finalizes queued jobs, and refuses a new batch", function()
        sdk.select({ sdk.photo(1), sdk.photo(2) })
        sdk.maskHook = function() sdk.tasksApi.sleep(100) end
        local first = pipeline.start({ profile = "full" })
        local queued = pipeline.start({ profile = "full" })
        sdk.advance(20)
        local result = pipeline.status({ jobId = first.jobId })
        assert.are.equal("FAILED", result.status)
        assert.are.equal(1, result.failed)
        assert.are.equal(1, result.skipped)
        assert.is_true(result.restartRequired)
        assert.are.equal("FAILED", pipeline.status({ jobId = queued.jobId }).status)
        assert.has_error(function() pipeline.start({ profile = "full" }) end)
        assert.are.same({ 1 }, sdk.maskCalls)
        assert.are.same({ 1 }, sdk.enhanceCalls)
    end)

    it("immediately cancels queued work while preserving the active job", function()
        sdk.select({ sdk.photo(1) })
        sdk.enhanceHook = function() sdk.tasksApi.sleep(4) end
        local active = pipeline.start({ profile = "full" })
        local queued = pipeline.start({ profile = "full" })
        sdk.advance(1)
        assert.are.equal(active.jobId, pipeline.preferredJobId(queued.jobId))
        local result = pipeline.cancel({ jobId = queued.jobId })
        assert.are.equal("CANCELLED", result.status)
        sdk.advance(20)
        assert.are.equal(1, pipeline.status({ jobId = active.jobId }).completed)
        assert.are.same({ 1 }, sdk.enhanceCalls)
    end)

    it("cleans up an abandoned worker context and runs later work", function()
        sdk.select({ sdk.photo(1, { available = false }) })
        local interrupted = pipeline.start({ profile = "full" })
        sdk.advance(0.5)
        sdk.abortTask("LightroomAIBatchWorker")
        sdk.advance(2)
        assert.are.equal("FAILED", pipeline.status({ jobId = interrupted.jobId }).status)
        sdk.select({ sdk.photo(2) })
        local nextJob = pipeline.start({ profile = "full" })
        sdk.advance(20)
        assert.are.equal(1, pipeline.status({ jobId = nextJob.jobId }).completed)
    end)

    it("skips processed photos without applying presets again", function()
        local photo = sdk.photo(1, { denoise = true, metadata = { pipelineVersion = "1.0.0", processed = "true",
            autoToneStatus = "COMPLETE", subjectStatus = "COMPLETE", landscapeStatus = "COMPLETE" } })
        sdk.select({ photo })
        local submitted = pipeline.start({ profile = "full" })
        sdk.advance(10)
        assert.are.equal(1, pipeline.status({ jobId = submitted.jobId }).skipped)
        assert.is_nil(photo.presetCalls)
        assert.are.same({}, sdk.enhanceCalls)
    end)

    it("keeps an abandoned worker's native call gated until its late return", function()
        sdk.select({ sdk.photo(1) })
        sdk.enhanceHook = function() sdk.tasksApi.sleep(4) end
        local interrupted = pipeline.start({ profile = "full" })
        sdk.advance(1)
        sdk.abortTask("LightroomAIBatchWorker")
        sdk.advance(0.1)
        assert.is_true(pipeline.status({ jobId = interrupted.jobId }).restartRequired)
        assert.has_error(function() pipeline.start({ profile = "full" }) end)
        sdk.advance(5)
        local returned = pipeline.status({ jobId = interrupted.jobId })
        assert.is_false(returned.restartRequired)
        assert.is_true(returned.lastOperation.callReturned)
        sdk.select({ sdk.photo(2) })
        local nextJob = pipeline.start({ profile = "full" })
        sdk.advance(20)
        assert.are.equal(1, pipeline.status({ jobId = nextJob.jobId }).completed)
    end)

    it("repairs stale Denoise without reapplying completed tone or presets", function()
        local photo = sdk.photo(1, { metadata = { pipelineVersion = "1.0.0", processed = "true",
            denoiseStatus = "COMPLETE", autoToneStatus = "COMPLETE",
            subjectStatus = "COMPLETE", landscapeStatus = "COMPLETE" } })
        sdk.select({ photo })
        local submitted = pipeline.start({ profile = "full" })
        sdk.advance(20)
        assert.are.equal(1, pipeline.status({ jobId = submitted.jobId }).completed)
        assert.are.same({ 1 }, sdk.enhanceCalls)
        assert.are.same({ 1 }, sdk.maskCalls)
        assert.is_nil(photo.presetCalls)
        assert.is_nil(photo.autoCalls)
        assert.are.same({}, sdk.cleanupCalls)
        assert.are.equal("1.0.0", photo.metadata.pipelineVersion)
    end)

    it("finishes empty mask cleanup after an interrupted completed Landscape stage", function()
        local photo = sdk.photo(1, { denoise = true, metadata = {
            pipelineVersion = "1.0.0", processed = "false", denoiseStatus = "COMPLETE",
            autoToneStatus = "COMPLETE", subjectStatus = "COMPLETE", landscapeStatus = "COMPLETE" } })
        sdk.select({ photo })
        local submitted = pipeline.start({ profile = "full" })
        sdk.advance(20)
        local result = pipeline.status({ jobId = submitted.jobId })
        assert.are.equal(1, result.completed)
        assert.are.same({ 1 }, sdk.maskCalls)
        assert.are.same({ 1 }, sdk.cleanupCalls)
        assert.are.same({}, sdk.enhanceCalls)
        assert.is_nil(photo.presetCalls)
        assert.is_nil(photo.autoCalls)
        assert.are.equal("true", photo.metadata.processed)
    end)

    it("invalidates processed state during a forced rerun and safely resumes after cancellation", function()
        local photo = sdk.photo(1, { denoise = true, metadata = {
            pipelineVersion = "1.0.0", processed = "true", denoiseStatus = "COMPLETE",
            autoToneStatus = "COMPLETE", subjectStatus = "COMPLETE", landscapeStatus = "COMPLETE" } })
        sdk.select({ photo })
        sdk.maskHook = function() sdk.tasksApi.sleep(1) end
        local interrupted = pipeline.start({ profile = "full", force = true })
        for _ = 1, 40 do
            sdk.advance(0.25)
            if #sdk.maskCalls > 0 then break end
        end
        assert.are.same({ 1 }, sdk.maskCalls)
        assert.are.equal("false", photo.metadata.processed)
        pipeline.cancel({ jobId = interrupted.jobId })
        sdk.advance(10)
        local cancelled = pipeline.status({ jobId = interrupted.jobId })
        assert.are.equal("CANCELLED", cancelled.status)
        assert.is_false(cancelled.workerRunning)
        assert.is_false(cancelled.restartRequired)
        assert.are.equal("false", photo.metadata.processed)
        local presetCalls, autoCalls = photo.presetCalls, photo.autoCalls
        sdk.maskHook = nil
        local resumed = pipeline.start({ profile = "full" })
        sdk.advance(20)
        assert.are.equal(1, pipeline.status({ jobId = resumed.jobId }).completed)
        assert.are.same({ 1, 1 }, sdk.maskCalls)
        assert.are.same({ 1 }, sdk.cleanupCalls)
        assert.are.equal(presetCalls, photo.presetCalls)
        assert.are.equal(autoCalls, photo.autoCalls)
        assert.are.equal("true", photo.metadata.processed)
    end)
end)
